    <div class="reminder">
      <h5 class="fw-semibold mb-3">Pro-Tips for Success</h5>
      <ul class="mb-0">
        <li><strong>Keep it Short:</strong> 20 minutes of focused, "rapt attention" is better than an hour of bored staring.</li>
        <li><strong>Celebrate the "Near Misses":</strong> If they get a word wrong, don't focus on the error. Focus on the part they <em>did</em> get right, then fix the rest.</li>
        <li><strong>Use Visual Aids:</strong> Post "Words of the Week" on the fridge or bathroom mirror to encourage passive retention.</li>
