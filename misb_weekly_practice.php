<!-- Daily Breakdown -->
<section id="breakdown" class="py-5">
  <div class="container">
    <h2 class="section-title mb-4">Daily Breakdown: How to Execute</h2>

    <div class="row g-4">
      <div class="col-md-6">
        <div class="card-soft">
          <strong>Monday: Word Discovery (The "Roots")</strong><br>
          Don't just look at the letters. Explore where the word comes from (Latin, Greek, etc.).<br>
          <strong>Activity:</strong> Pick 5 words. Find their "origin story." Understanding the root helps in predicting the spelling of thousands of other words.
        </div>
      </div>
      
      <div class="col-md-6">
        <div class="card-soft">
          <strong>Tuesday: Contextual Meaning (Beyond the Dictionary)</strong><br>
          MISB values "language comprehension." Knowing how to spell a word is useless if you can't use it.<br>
          <strong>Activity:</strong> Create "Action Cards." Write a word on one side and a funny, relatable sentence using it on the other.
        </div>
      </div>

      <div class="col-md-6">
        <div class="card-soft">
          <strong>Wednesday: Game Day (Maintaining Rapt Attention)</strong><br>
          This is the heart of the MISB method.<br>
          <strong>Activity:</strong> Use Scrabble, crosswords, or online word-building games. This utilizes the student's aspirations for winning to drive learning.
        </div>
      </div>

      <div class="col-md-6">
        <div class="card-soft">
          <strong>Thursday: The Listening Ear (Auditory Skills)</strong><br>
          Spelling bees are often oral. You must hear the nuances in pronunciation.<br>
          <strong>Activity:</strong> Have a parent or sibling read words aloud. The student must identify the number of syllables and the "tricky" vowel sounds before spelling.
        </div>
      </div>

      <div class="col-md-6">
        <div class="card-soft">
          <strong>Friday: Systematic Review (Patterns)</strong><br>
          English can be messy, but it has patterns (e.g., -tion vs. -sion).<br>
          <strong>Activity:</strong> Group words by their suffixes or prefixes. This creates a structured understanding of the language.
        </div>
      </div>

      <div class="col-md-6">
        <div class="card-soft">
          <strong>Saturday: The Simulation (Building Confidence)</strong><br>
          Replicate the competitive environment to reduce "stage fright."<br>
          <strong>Activity:</strong> Set a timer. Conduct a mini-competition with a "buzzer" (a bell or a desk tap). Focus on the experience and the interaction rather than just the score.
        </div>
      </div>

      <div class="col-12">
        <div class="card-soft">
          <strong>Sunday: The "Bridge" Reflection</strong><br>
          <strong>Activity:</strong> Let the student pick their "Favorite Word of the Week." Discuss how that word helps them express themselves better. This reinforces the idea that language is a bridge to a better world.
        </div>
      </div>
    </div>
  </div>
</section>

<!-- Pro Tips -->
<section id="tips" class="py-5 bg-light"> 
